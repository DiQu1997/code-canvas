def A(a, b=None):
    """note / at 的 ref= 用的锚点：文件:行 或 文件:起-止。"""
    return '%s:%s' % (SRC, a if b is None else '%d-%d' % (a, b))


def R(a, b=None):
    """写在文字里的锚点（迷你语法，要带反引号）。"""
    return '`%s`' % A(a, b)


